    assert r["Pre Carrier"] == "null"
    assert r["Vessel"] == r["Trunk Vessel"] == "EVER MAGNA 1382-006E"
    assert r["ETD_Trunk"] == "19/10/2026"
    assert r["Port Cargo Cut-off"] == "17/10/2026 17:00"
